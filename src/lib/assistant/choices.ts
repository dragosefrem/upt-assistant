import { z } from "zod";

const date = z.iso.date();
const clock = z.string().regex(/^(?:(?:[01]\d|2[0-3]):[0-5]\d|24:00)$/);
const period = z.object({ date, start: clock, end: clock });

/**
 * A tappable option the assistant shows under a reply: a proposed time slot or a quick
 * answer such as "Yes, add it". Shared by the server and the chat UI, so it must not
 * import anything server-only.
 */
export interface AssistantChoice {
  /** Button text. */
  label: string;
  /** Sent as the student's next message when the choice is tapped. */
  reply: string;
  /** Set when the choice is a time slot: YYYY-MM-DD, HH:MM, HH:MM. */
  date?: string;
  start?: string;
  end?: string;
}

/** A button under a reply that opens a page of the app (a walkthrough, a group event). */
export interface AssistantLink {
  label: string;
  /** In-app address starting with "/". */
  href: string;
}

/** Reads links stored with a chat message; only in-app addresses survive. */
export function parseLinks(json: string | null | undefined): AssistantLink[] | undefined {
  if (!json) return undefined;
  try {
    const list = JSON.parse(json) as unknown;
    if (!Array.isArray(list)) return undefined;
    const valid = list.filter(
      (l): l is AssistantLink => !!l && typeof l === "object" && typeof l.label === "string" && typeof l.href === "string" && /^\/(?!\/)/.test(l.href),
    );
    return valid.length ? valid : undefined;
  } catch {
    return undefined;
  }
}

/** One event on the day shown in a change preview. */
export interface PreviewEvent {
  title: string;
  kind: string;
  start: string;
  end: string;
  room: string | null;
  /** Whether the proposed time overlaps this event. */
  overlaps: boolean;
}

/**
 * A proposed change to the student's calendar, shown as that day's timeline with the
 * change highlighted. Nothing is saved until the student accepts it.
 */
export interface DayPreview {
  status: "pending" | "accepted";
  action: "add" | "move";
  title: string;
  /** The day shown, YYYY-MM-DD; for a weekly event, its next occurrence. */
  date: string;
  weekly: boolean;
  /** The review card contains the full response generated by the time editor. */
  textIsTranscript?: true;
  roomChange?: { from: string | null; to: string };
  start: string;
  end: string;
  /** Where a moved event is now. */
  from?: { date: string; start: string; end: string };
  /** Everything else on that day. */
  events: PreviewEvent[];
  /** Conflicts on another occurrence of a weekly proposal. */
  otherClashes?: Array<{ date: string; title: string; start: string; end: string }>;
  /** Free times of the same duration on the proposed day. */
  alternatives?: Array<{ start: string; end: string }>;
}

/** The stored form also records the exact change to apply on acceptance; it never leaves the server. */
export interface StoredPreview extends DayPreview {
  change: { tool: "add_personal_event" | "move_personal_event" | "move_class_once" | "move_class"; args: Record<string, unknown> };
}

const storedPreview = z.object({
  status: z.enum(["pending", "accepted"]), action: z.enum(["add", "move"]), title: z.string(),
  date, weekly: z.boolean(), start: clock, end: clock, from: period.optional(),
  textIsTranscript: z.literal(true).optional(),
  roomChange: z.object({ from: z.string().nullable(), to: z.string() }).optional(),
  events: z.array(z.object({ title: z.string(), kind: z.string(), start: clock, end: clock, room: z.string().nullable(), overlaps: z.boolean() })),
  otherClashes: z.array(period.extend({ title: z.string() })).optional(),
  alternatives: z.array(z.object({ start: clock, end: clock })).max(2).optional(),
  change: z.object({ tool: z.enum(["add_personal_event", "move_personal_event", "move_class_once", "move_class"]), args: z.record(z.string(), z.unknown()) }),
});

export function parsePreview(json: string | null | undefined): StoredPreview | undefined {
  if (!json) return undefined;
  try {
    const result = storedPreview.safeParse(JSON.parse(json));
    return result.success ? result.data : undefined;
  } catch {
    return undefined;
  }
}

/** What the browser may see of a preview. */
export function publicPreview(p: StoredPreview | undefined): DayPreview | undefined {
  if (!p) return undefined;
  const { change: _change, ...rest } = p; // eslint-disable-line @typescript-eslint/no-unused-vars
  return rest;
}

/** Reads choices stored with a chat message; anything malformed yields none. */
export function parseChoices(json: string | null | undefined): AssistantChoice[] | undefined {
  if (!json) return undefined;
  try {
    const list = JSON.parse(json) as unknown;
    if (!Array.isArray(list)) return undefined;
    const valid: AssistantChoice[] = [];
    for (const c of list.slice(0, 6)) {
      if (!c || typeof c.label !== "string" || !c.label || typeof c.reply !== "string" || !c.reply) continue;
      const slot = date.safeParse(c.date).success && clock.safeParse(c.start).success;
      const choice: AssistantChoice = { label: c.label, reply: c.reply };
      if (slot) {
        choice.date = c.date;
        choice.start = c.start;
        if (clock.safeParse(c.end).success && c.end > c.start) choice.end = c.end;
      }
      valid.push(choice);
    }
    return valid.length ? valid : undefined;
  } catch {
    return undefined;
  }
}
